"""DB 스택 MySQL 8: 같은 데이터 모델에서 MySQL DDL·예시 데이터·Spring 틀을 만든다. PostgreSQL 결과는 바뀌지 않는다 (LLM 없음)."""
import pytest

from test_develop import _spec

from app.agents.roles import builder, developer
from app.agents.tools import scaffold, stacks
from app.agents.tools.ddl import render_script
from app.agents.tools.sample_data import seed_sql
from app.schemas.data_model import Attribute, CheckRule, DataModel, Entity

DB = "backend/src/main/java/app/common/Db.java"
ACCOUNTS = "backend/src/main/java/app/auth/Accounts.java"


def _model():
    team = Entity(entity_id="team", label="팀", description="팀 한 건", attributes=[
        Attribute(name="team_id", data_type="bigint", nullable=False, primary_key=True, label="팀 ID"),
        Attribute(name="code", data_type="text", nullable=False, unique=True, label="코드"),
        Attribute(name="rank", data_type="integer", label="순위"),   # MySQL 예약어 (PostgreSQL은 아님)
        Attribute(name="memo", data_type="varchar", length=100, label="메모", description="역슬래시 \\ 포함"),
    ])
    task = Entity(entity_id="task", label="작업", attributes=[
        Attribute(name="task_id", data_type="bigint", nullable=False, primary_key=True),
        Attribute(name="team_id", data_type="bigint", nullable=False, references="team"),
        Attribute(name="status", data_type="varchar", length=20, nullable=False, allowed_values=["대기", "완료"]),
        Attribute(name="done", data_type="boolean", nullable=False),
        Attribute(name="amount", data_type="decimal"),
        Attribute(name="due_at", data_type="timestamp"),
        Attribute(name="extra", data_type="jsonb"),
        Attribute(name="ref", data_type="uuid"),
        Attribute(name="body", data_type="varchar", length=8000),
        Attribute(name="note", data_type="varchar", length=8000),
    ], checks=[CheckRule(column="amount", op=">=", value="0")])
    return DataModel(entities=[team, task], relations=[])


def test_mysql_ddl_uses_mysql_types_keys_and_comments():
    sql = render_script(_model(), "1.0", "mysql")
    assert "dialect=mysql" in sql and "SET NAMES utf8mb4;" in sql
    assert "team_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '팀 ID'" in sql
    assert "code VARCHAR(255) NOT NULL" in sql, "UNIQUE인 TEXT는 키 길이가 없어 VARCHAR(255)"
    assert "`rank` INT" in sql, "MySQL 예약어는 백틱"
    assert "'메모 - 역슬래시 \\\\ 포함'" in sql, "MySQL 문자열은 역슬래시도 이스케이프"
    for text in ("done BOOLEAN NOT NULL", "amount DECIMAL(18,2)", "due_at DATETIME(6)", "extra JSON", "ref CHAR(36)",
                 "CHECK (status IN ('대기', '완료'))", "CHECK (amount >= 0)", "ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='팀 - 팀 한 건'"):
        assert text in sql, text
    assert "body TEXT" in sql and "note VARCHAR(8000)" in sql, "한 행 VARCHAR 한도를 넘으면 긴 칸 하나를 TEXT로"
    for pg in ("IDENTITY", "TIMESTAMPTZ", "JSONB", "COMMENT ON", "NUMERIC"):
        assert pg not in sql, pg
    assert sql.index("CREATE INDEX ix_task_team_id") < sql.index("ADD CONSTRAINT fk_task_team_id FOREIGN KEY (team_id) REFERENCES team (team_id)")
    postgres = render_script(_model(), "1.0")
    assert "GENERATED BY DEFAULT AS IDENTITY" in postgres and "COMMENT ON TABLE team" in postgres and "`" not in postgres


def test_mysql_ddl_drops_auto_increment_check_and_shortens_long_keys():
    org = Entity(entity_id="org", attributes=[
        Attribute(name="org_id", data_type="bigint", nullable=False, primary_key=True),
        Attribute(name="parent_id", data_type="bigint", references="org"),
        Attribute(name="path", data_type="varchar", length=1000, unique=True),
    ], checks=[CheckRule(column="parent_id", op="<>", value="org_id")])
    sql = render_script(DataModel(entities=[org], relations=[]), "1.0", "mysql")
    assert "-- MySQL에서 뺀 제약 (자동 번호 컬럼을 가리키는 CHECK): CONSTRAINT ck_org_parent_id_ne_org_id" in sql, "MySQL 오류 3818"
    assert "    CONSTRAINT ck_org_parent_id_ne_org_id" not in sql
    assert "UNIQUE (path(768))" in sql and "path VARCHAR(1000)" in sql, "키 길이 3,072바이트 한도: 값 길이는 그대로"
    assert "CHECK (parent_id <> org_id)" in render_script(DataModel(entities=[org], relations=[]), "1.0"), "PostgreSQL은 그대로"


def test_mysql_seed_literals():
    rows = {"team": [{"team_id": 1, "code": "T-1", "rank": 1, "memo": "a\\b'c"}],
            "task": [{"task_id": 1, "team_id": 1, "status": "대기", "done": True, "amount": 10, "due_at": "2026-03-02T09:00:00+09:00",
                      "extra": {"k": "v"}, "ref": None, "body": "x", "note": "y"}]}
    sql = seed_sql(_model(), rows, "mysql")
    assert sql.startswith("-- ") and "START TRANSACTION;" in sql and "RESTART" not in sql
    assert "INSERT INTO team (team_id, code, `rank`, memo) VALUES (1, 'T-1', 1, 'a\\\\b''c');" in sql
    assert "TRUE, 10, '2026-03-02 09:00:00', '{\"k\": \"v\"}', NULL" in sql
    postgres = seed_sql(_model(), rows)
    assert "BEGIN;" in postgres and "'2026-03-02T09:00:00+09:00'" in postgres and "'a\\b''c'" in postgres and "RESTART WITH" in postgres


def test_mysql_stack_renders_mysql_app_and_postgres_stays_same(sample_doc):
    spec = _spec(sample_doc)
    postgres, _ = scaffold.render_app(spec)
    spec.parts = {**spec.parts, "database": "mysql"}
    assert "mysql" in stacks.TEMPLATED["database"] and scaffold.has_backend(spec)
    mysql, _ = scaffold.render_app(spec)
    assert sorted(mysql) == sorted(postgres), "같은 파일 목록"
    assert "image: mysql:8" in mysql["docker-compose.yml"] and "jdbc:mysql://db:3306/app" in mysql["docker-compose.yml"]
    assert "dialect=mysql" in mysql["db/schema.sql"] and "AUTO_INCREMENT" in mysql["db/schema.sql"]
    assert mysql["spec/schema.sql"] == postgres["spec/schema.sql"], "스펙 문서는 설계 그대로 (PostgreSQL)"
    assert "mysql-connector-j" in mysql["backend/pom.xml"] and "org.postgresql" not in mysql["backend/pom.xml"]
    assert "sql_mode = 'ANSI" in mysql["backend/src/main/resources/application.yml"]
    assert ") RETURNING " not in mysql[DB] and "GeneratedKeyHolder" in mysql[DB] and "md5(random()::text)" not in mysql[DB]
    assert "app_auth." not in mysql[ACCOUNTS] and "timestamptz" not in mysql[ACCOUNTS] and "CREATE SCHEMA" not in mysql[ACCOUNTS]
    assert "AS char)" in mysql["backend/src/main/java/app/api/LookupController.java"]
    assert "MySQL만" in mysql["README.md"]
    # PostgreSQL: 틀 파일 그대로, MySQL을 한 번 만든 뒤에도 같은 결과
    assert postgres[DB] == (scaffold.TEMPLATES / DB).read_text(encoding="utf-8")
    assert postgres["db/schema.sql"] == spec.read("schema.sql") and "image: postgres:16" in postgres["docker-compose.yml"]
    spec.parts = {**spec.parts, "database": "postgresql"}
    assert scaffold.render_app(spec)[0] == postgres


